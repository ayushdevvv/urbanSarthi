const reverseTranslations = Object.fromEntries(Object.entries(HI_TRANSLATIONS).map(([en, hi]) => [hi, en]));
const ATTRIBUTE_NAMES = ['aria-label', 'title', 'placeholder', 'alt'];
const trimShape = (value) => ({ leading: value.match(/^\s*/)?.[0] || '', trailing: value.match(/\s*$/)?.[0] || '' });

function translateTextNode(node, language) {
  const current = node.nodeValue || '';
  const trimmed = current.trim();
  if (!trimmed) return;
  const translatedBefore = node.__urbanSaarthiTranslated;
  let original = node.__urbanSaarthiOriginal;
  if (original == null || (current !== translatedBefore && current.trim() !== translatedBefore?.trim())) {
    original = reverseTranslations[trimmed] || current;
    node.__urbanSaarthiOriginal = original;
  }
  const originalTrimmed = original.trim();
  const shape = trimShape(original);
  const nextText = language === 'HI' ? (HI_TRANSLATIONS[originalTrimmed] || originalTrimmed) : originalTrimmed;
  const nextValue = shape.leading + nextText + shape.trailing;
  if (node.nodeValue !== nextValue) {
    node.__urbanSaarthiTranslated = nextValue;
    node.nodeValue = nextValue;
  } else {
    node.__urbanSaarthiTranslated = nextValue;
  }
}

export function installLanguage(language) {
  if (typeof document === 'undefined') return () => {};
  const root = document.querySelector('#root');
  if (!root) return () => {};
  const applyAttributes = (element) => {
    for (const attribute of ATTRIBUTE_NAMES) {
      if (!element.hasAttribute(attribute)) continue;
      const current = element.getAttribute(attribute) || '';
      const translatedBefore = element[`__urbanSaarthiTranslated_${attribute}`];
      let original = element[`__urbanSaarthiOriginal_${attribute}`];
      if (original == null || (current !== translatedBefore && current !== HI_TRANSLATIONS[original])) {
        original = reverseTranslations[current] || current;
        element[`__urbanSaarthiOriginal_${attribute}`] = original;
      }
      const next = language === 'HI' ? (HI_TRANSLATIONS[original] || original) : original;
      element[`__urbanSaarthiTranslated_${attribute}`] = next;
      if (current !== next) element.setAttribute(attribute, next);
    }
  };
  const walk = (node) => {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, language);
    else if (node.nodeType === Node.ELEMENT_NODE) {
      applyAttributes(node);
      node.childNodes.forEach(walk);
    }
  };
  document.documentElement.lang = language === 'HI' ? 'hi' : 'en';
  walk(root);
  let scheduled = false;
  const observer = new MutationObserver((mutations) => {
    if (scheduled) return;
    scheduled = true;
    queueMicrotask(() => {
      scheduled = false;
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') translateTextNode(mutation.target, language);
        else if (mutation.type === 'attributes') applyAttributes(mutation.target);
        else mutation.addedNodes?.forEach(walk);
      }
    });
  });
  observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRIBUTE_NAMES });
  return () => observer.disconnect();
}
